def readProjectFiles():
    """Decode the complete project snapshot stored in this file."""

    compressed = base64.b64decode(PROJECT_FILES)
    content = zlib.decompress(compressed).decode("utf-8")

    return json.loads(content)


def writeProject(baseDirectory):
    """Create a standalone copy of this application."""

    projectDirectory = (
        Path(baseDirectory).expanduser().resolve()
        / PROJECT_NAME
    )
    projectDirectory.mkdir(parents=True, exist_ok=True)

    for relativePath, content in readProjectFiles().items():
        target = projectDirectory / relativePath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    # Keep the generated copy portable by putting this generator inside it.
    generatorCopy = projectDirectory / "generate_project.py"
    generatorCopy.write_text(
        Path(__file__).read_text(encoding="utf-8"),
        encoding="utf-8",
    )

    return projectDirectory


if __name__ == "__main__":
    destination = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
    output = writeProject(destination)
    print(f"Created project: {output}")
