def _read_project_files():
    """Decode the embedded project snapshot."""

    compressed = base64.b64decode(PROJECT_FILES)
    content = zlib.decompress(compressed).decode("utf-8")
    return json.loads(content)


def write_project(base_dir):
    """Create the semantic project folder and write every embedded file."""

    project_dir = Path(base_dir).expanduser().resolve() / PROJECT_NAME
    project_dir.mkdir(parents=True, exist_ok=True)

    for relative_path, content in _read_project_files().items():
        target = project_dir / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    # Include the generator so the reconstructed project remains portable.
    generator_copy = project_dir / "generate_project.py"
    generator_copy.write_text(
        Path(__file__).read_text(encoding="utf-8"),
        encoding="utf-8",
    )
    return project_dir


